export type Key = keyof Dict
export const dicts: Record<Lang, Dict> = { en, nl }

export function makeT(lang: Lang) {
  const d = dicts[lang]
  return <K extends Key>(k: K, ...args: Dict[K] extends (...a: infer A) => string ? A : []): string => {
    const v = d[k] as unknown
    return typeof v === 'function' ? (v as (...a: unknown[]) => string)(...args) : (v as string)
  }
}

export type T = ReturnType<typeof makeT>

export function fmtDate(iso: string | null, lang: Lang, never: string) {
  if (!iso) return never
  const d = new Date(iso)
  const days = Math.floor((Date.now() - d.getTime()) / 86400000)
  const rtf = new Intl.RelativeTimeFormat(lang, { numeric: 'auto' })
  if (days < 1) return d.toLocaleTimeString(lang, { hour: '2-digit', minute: '2-digit' })
  if (days < 30) return rtf.format(-days, 'day')
  return d.toLocaleDateString(lang, { day: 'numeric', month: 'short', year: 'numeric' })
}
